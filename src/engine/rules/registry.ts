export const RULES: Rule[] = applyPackMetadata(RULES_RAW);

export const RULE_BY_ID: Record<string, Rule> = Object.fromEntries(RULES.map((r) => [r.id, r]));

export const FORMS = [...new Set(RULES.map((r) => r.form))].sort();

export function rulesForLine(path: string): Rule[] {
  return RULES.filter((r) =>
    r.appliesTo.some((p) => p === path || p === `${path.split('.')[0]}.*` || (p.endsWith('.*') && path.startsWith(p.slice(0, -1)))),
  );
}

export function linesForRule(id: string): string[] {
  return RULE_BY_ID[id]?.appliesTo ?? [];
}
